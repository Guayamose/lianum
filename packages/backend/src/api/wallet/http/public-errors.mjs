const maxCodeLength = Math.max(...[...publicCodes].map(code => code.length));
/** @param {object} value @param {PropertyKey} key @returns {unknown} */
const ownData = (value, key) => {
  const descriptor = Object.getOwnPropertyDescriptor(value, key);
  return descriptor && Object.hasOwn(descriptor, 'value') ? descriptor.value : undefined;
};

/** @param {unknown} error @param {boolean} [native] @returns {string} */
export function publicCode(error, native = false) {
  const fallback = native ? 'NATIVE_CLAIM_OPERATION_FAILED' : 'WALLET_OPERATION_FAILED';
  try {
    // isProxy also rejects revoked proxies without invoking traps. Do not read
    // inherited properties, coerce values, traverse causes or inspect stacks.
    if (!error || typeof error !== 'object' || types.isProxy(error)) return fallback;
    const code = ownData(error, 'code');
    const message = ownData(error, 'message');
    const explicitAssertion = types.isNativeError(error) && code === 'ERR_ASSERTION'
      && ownData(error, 'generatedMessage') === false;
    // Owned Node assertions append actual/expected details to custom labels.
    // Inspect at most one code-width prefix; never return any diagnostic suffix.
    const label = explicitAssertion && typeof message === 'string'
      ? message.slice(0, maxCodeLength + 1).split('\n', 1)[0] : code ?? message;
    return typeof label === 'string' && label.length <= maxCodeLength && publicCodes.has(label)
      ? label : fallback;
  } catch { return fallback; }
}
