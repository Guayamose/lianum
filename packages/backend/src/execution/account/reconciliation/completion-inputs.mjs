/** Scoped N32/T138 witness preparation. The caller supplies pinned compiled
 * ABIs and hashing. No proofs, backend, signing key or native runtime here.
 * Root provenance, fresh state and atomic verification of T + four N proofs
 * remain external requirements; opening a commitment establishes none of them. */
import assert from 'node:assert/strict';
import { createCommitmentCodec, exactRecord, fixedArray, bytes32, canonicalField,
  validateStruct, structToNoir, digestBytes, digestWords, ZERO } from '@lianum/components/encoding/commitments';
import { validateStatement } from '@lianum/components/encoding/statements';
import { cloneInput, frozenInput, inputUint, inputPath } from "@lianum/components/plain-input";
import { validateFlatInputs } from "../preparation/readiness-inputs.mjs";
import { nativeReceiptReadOpening, nativeReceiptCommitment, nativeReceiptToNoir, RECEIPT_HASH_FIELDS }
  from '@lianum/engine/execution/native/state/native-receipt';
import { nativeTransferActionCommitment } from '@lianum/engine/execution/native/dispatch/native-capsules';
import { verifyPrivateNotePath } from '@lianum/engine/notes/private-note-tree';
import { receiptKeyCommitment, terminalReceiptTag } from '@lianum/components/framing';

const snake = name => name.replace(/[A-Z]/g, letter => '_' + letter.toLowerCase());
const RECEIPT_DIGESTS = [...RECEIPT_HASH_FIELDS, 'receiptKeyCommitment', 'receiptRho'];
function zeroReceipt() {
  return Object.fromEntries([...RECEIPT_HASH_FIELDS, 'validFrom', 'validUntil', 'receiptKeyCommitment', 'receiptRho']
    .map(name => [snake(name), name === 'validFrom' || name === 'validUntil' ? '0' : Array(32).fill(0)]));
}
function receiptOpening(value) {
  exactRecord(value, [...RECEIPT_HASH_FIELDS, 'validFrom', 'validUntil', 'receiptKeyCommitment', 'receiptRho']);
  RECEIPT_DIGESTS.forEach(name => bytes32(value[name], true));
  inputUint(value.validFrom); inputUint(value.validUntil);
  return nativeReceiptReadOpening(value);
}
function window(from, until, cutoff) {
  const start = inputUint(from), end = inputUint(until);
  assert.ok(start < end && end <= inputUint(cutoff), 'COMPLETION_WINDOW');
  return { from: start, until: end };
}
async function opening(codec, domain, envelope, name, supplied, expectedIndex) {
  exactRecord(supplied, ['value', 'blind', 'leaf', 'index', 'siblings']);
  assert.equal(supplied.index, expectedIndex, 'COMPLETION_LEAF_POSITION');
  bytes32(supplied.blind, true); canonicalField(supplied.leaf, true);
  fixedArray(supplied.siblings, 4); supplied.siblings.forEach(value => canonicalField(value));
  const value = validateStruct(name, supplied.value), leaf = await codec[name + 'Leaf'](domain, value, supplied.blind);
  assert.equal(leaf, supplied.leaf, 'COMPLETION_LEAF_COMMITMENT');
  assert.equal(await codec.membershipRoot(domain, 1, leaf, supplied.siblings, expectedIndex), envelope, 'COMPLETION_ENVELOPE_PATH');
  return value;
}
async function context(input, codec, kind) {
  const packet = input.packet;
  exactRecord(packet, ['domainCommitment', 'envelope', 'domain', 'core', kind,
    ...(kind === 'local' ? ['action', 'receiptSpendSecret'] : ['payouts'])]);
  const domain = validateStruct('domain', packet.domain), d = packet.domainCommitment;
  canonicalField(d, true); canonicalField(packet.envelope, true);
  assert.equal(await codec.domainCommitment(domain), d, 'COMPLETION_DOMAIN');
  const authorization = inputPath(input.authorization, 6, true);
  const authLeaf = await codec.authorizationLeaf(d, packet.envelope);
  assert.equal(await codec.membershipRoot(d, 0, authLeaf, authorization.siblings, authorization.index),
    authorization.root, 'COMPLETION_AUTHORIZATION_PATH');
  const core = await opening(codec, d, packet.envelope, 'core', packet.core, 0);
  const own = validateStruct(kind, packet[kind].value);
  await opening(codec, d, packet.envelope, kind, packet[kind], kind === 'local' ? 4 + Number(own.slot) : 3);
  const common = { domain: structToNoir('domain', domain), envelope: digestBytes(packet.envelope),
    authorization_siblings: authorization.siblings.map(digestBytes), authorization_index: authorization.index,
    core: structToNoir('core', core), core_blind: digestBytes(packet.core.blind), core_siblings: packet.core.siblings.map(digestBytes) };
  return { packet, domain, d, core, own, authorization, common };
}

/** Active N receives only its own original ReceiptRead and purpose8 path.
 * Padding requires null receiptOpening/receiptPath, zero own secret, null
 * action, and emits every original zero receipt/path/index witness itself.
 * Completion blind is fresh caller-owned B32, never generated by this codec. */
export async function buildNodeInputs(raw, options) {
  exactRecord(options, ['hashFields', 'abi']);
  const input = cloneInput(raw);
  exactRecord(input, ['packet', 'authorization', 'stateOpening', 'evidenceState', 'revokedEntries',
    'receiptOpening', 'receiptPath', 'validFrom', 'validUntil', 'completionBlind']);
  const codec = createCommitmentCodec({ hashFields: options.hashFields });
  const c = await context(input, codec, 'local');
  const { packet, domain, d, core, own: local } = c;
  const period = window(input.validFrom, input.validUntil, core.settleBefore);
  bytes32(local.payoutCommitment, true); bytes32(input.completionBlind, true);
  canonicalField(input.evidenceState);
  const state = validateStruct('evidenceState', input.stateOpening);
  assert.equal(state.hubDomain, domain.hubDomain, 'COMPLETION_STATE_HUB');
  assert.equal(state.registryCommitment, domain.registryCommitment, 'COMPLETION_STATE_REGISTRY');
  assert.equal(await codec.evidenceStateDigest(d, state), input.evidenceState, 'COMPLETION_EVIDENCE_STATE');
  fixedArray(input.revokedEntries, 64);
  assert.equal(await codec.revokedDigest(d, domain.hubDomain, input.revokedEntries, state.revokedCount),
    state.revokedDigest, 'COMPLETION_REVOKED_DIGEST');
  let ownReceipt, receiptSiblings, receiptIndex, tag;
  if (local.active) {
    const receipt = receiptOpening(input.receiptOpening), path = inputPath(input.receiptPath, 6, true);
    for (const name of ['hubDomain', 'registryCommitment', 'scope', 'policy'])
      assert.equal(receipt[name], domain[name], 'COMPLETION_RECEIPT_DOMAIN');
    for (const name of ['localCommitment', 'dispatchId', 'chainDomain', 'evidencePolicy', 'actionCommitment',
      'payoutCommitment', 'receiptKeyCommitment', 'receiptRho'])
      assert.equal(receipt[name], local[name], 'COMPLETION_RECEIPT_LOCAL');
    assert.ok(inputUint(receipt.validFrom) <= period.from && period.until <= inputUint(receipt.validUntil), 'COMPLETION_RECEIPT_WINDOW');
    assert.ok(BigInt(path.index) < BigInt(state.receiptCount), 'COMPLETION_RECEIPT_COUNT');
    assert.equal(path.root, state.receiptRoot, 'COMPLETION_RECEIPT_ROOT');
    assert.ok(!input.revokedEntries.slice(0, Number(state.revokedCount)).includes(receipt.globalEffectId), 'COMPLETION_OWN_GID_REVOKED');
    // This is the one unchanged SHA ReceiptCM, used for both purpose8 and the
    // original SHA terminal tag. Do not pass the Poseidon leaf into that tag.
    const receiptCM = nativeReceiptCommitment(receipt);
    const leaf = await codec.receiptLeaf(d, receiptCM);
    assert.equal(await codec.membershipRoot(d, 2, leaf, path.siblings, path.index), state.receiptRoot, 'COMPLETION_RECEIPT_PATH');
    bytes32(packet.receiptSpendSecret, true);
    assert.equal(receiptKeyCommitment({ ledgerNamespace: domain.ledgerNamespace, secret: packet.receiptSpendSecret }),
      receipt.receiptKeyCommitment, 'COMPLETION_RECEIPT_KEY');
    tag = terminalReceiptTag({ ledgerNamespace: domain.ledgerNamespace,
      secret: packet.receiptSpendSecret, receiptCommitment: receiptCM });
    // U authenticated this local action. Keep the supplied local packet honest
    // without widening the frozen N ABI to include another action witness.
    assert.equal(nativeTransferActionCommitment(packet.action), local.actionCommitment, 'COMPLETION_LOCAL_ACTION');
    ownReceipt = nativeReceiptToNoir(receipt); receiptSiblings = path.siblings.map(digestBytes); receiptIndex = path.index;
  } else {
    assert.equal(input.receiptOpening, null, 'COMPLETION_PADDING_RECEIPT');
    assert.equal(input.receiptPath, null, 'COMPLETION_PADDING_PATH');
    assert.equal(packet.receiptSpendSecret, ZERO, 'COMPLETION_PADDING_SECRET');
    assert.equal(packet.action, null, 'COMPLETION_PADDING_ACTION');
    ownReceipt = zeroReceipt(); receiptSiblings = Array.from({ length: 6 }, () => Array(32).fill(0)); receiptIndex = 0;
    tag = local.dummyTerminalTag;
  }
  bytes32(tag, true);
  const completion = { hubDomain: domain.hubDomain, registryCommitment: domain.registryCommitment,
    evidenceState: input.evidenceState, context: core.context, payoutCommitment: local.payoutCommitment,
    terminalReceiptTag: tag, slot: local.slot, validFrom: input.validFrom, validUntil: input.validUntil };
  const completionCommitment = await codec.completionCommitment(d, packet.envelope, completion, input.completionBlind);
  const statement = { domainCommitment: d, authorizationRoot: c.authorization.root,
    evidenceState: input.evidenceState, completionCommitment };
  const inputs = { domain_commitment: digestWords(d), authorization_root: digestWords(c.authorization.root),
    evidence_state: digestWords(input.evidenceState), completion_commitment: digestWords(completionCommitment), ...c.common,
    local: structToNoir('local', local), local_blind: digestBytes(packet.local.blind), local_siblings: packet.local.siblings.map(digestBytes),
    completion: structToNoir('completion', completion), completion_blind: digestBytes(input.completionBlind),
    state_opening: structToNoir('evidenceState', state), own_receipt: ownReceipt,
    receipt_spend_secret: digestBytes(packet.receiptSpendSecret), receipt_siblings: receiptSiblings, receipt_index: receiptIndex,
    revoked_entries: input.revokedEntries.map(digestBytes) };
  const job = validateFlatInputs('node', options.abi, inputs, statement);
  // This is the ONLY N-specific private handoff to T: full sealed descriptor
  // and blind, bound to its exact public N statement and envelope. No receipt,
  // GID, action, local leaf, own secret, state opening or foreign graph data.
  return frozenInput({ ...job, completionOpening: { statement: cloneInput(job.statement), envelope: packet.envelope,
    completion, blind: input.completionBlind } });
}

/** T receives the assembler packet and exactly four ordered N seals. The
 * current assembler packet includes payout openings; only Core/Settlement
 * and sealed completions enter the actual T ABI. No receipt preimages needed. */
export async function buildSettlementInputs(raw, options) {
  exactRecord(options, ['hashFields', 'abi']);
  const input = cloneInput(raw);
  exactRecord(input, ['packet', 'authorization', 'evidenceState', 'reservePath', 'completions', 'validFrom', 'validUntil']);
  const codec = createCommitmentCodec({ hashFields: options.hashFields }), c = await context(input, codec, 'settlement');
  const { packet, domain, d, core, own: settlement } = c;
  canonicalField(input.evidenceState);
  for (const name of ['context', 'reserveCommitment', 'reserveNullifier', 'settleBefore'])
    assert.equal(settlement[name], core[name], 'COMPLETION_SETTLEMENT_CORE');
  const period = window(input.validFrom, input.validUntil, core.settleBefore);
  const reserve = inputPath(input.reservePath, 6);
  bytes32(core.reserveCommitment, true);
  assert.ok(verifyPrivateNotePath({ leaf: core.reserveCommitment, ...reserve }), 'COMPLETION_RESERVE_PATH');
  fixedArray(packet.payouts, 4); fixedArray(input.completions, 4);
  const completions = [], blinds = [], commitments = [], terminalTags = [], outputs = [];
  for (let slot = 0; slot < 4; slot++) {
    const payout = await opening(codec, d, packet.envelope, 'payout', packet.payouts[slot], 12 + slot);
    assert.equal(payout.slot, String(slot), 'COMPLETION_PAYOUT_SLOT');
    assert.equal(payout.commitment, settlement.outputs[slot], 'COMPLETION_PAYOUT_ORDER');
    const supplied = input.completions[slot];
    exactRecord(supplied, ['statement', 'envelope', 'completion', 'blind']);
    const n = validateStatement('node', supplied.statement), completion = validateStruct('completion', supplied.completion);
    canonicalField(supplied.envelope, true); bytes32(supplied.blind, true);
    assert.equal(supplied.envelope, packet.envelope, 'COMPLETION_SAME_ENVELOPE');
    assert.equal(n.domainCommitment, d, 'COMPLETION_SAME_DOMAIN');
    assert.equal(n.authorizationRoot, c.authorization.root, 'COMPLETION_SAME_AUTHORIZATION');
    assert.equal(n.evidenceState, input.evidenceState, 'COMPLETION_SAME_STATE');
    assert.equal(completion.slot, String(slot), 'COMPLETION_ORDER');
    assert.equal(completion.hubDomain, domain.hubDomain, 'COMPLETION_HUB');
    assert.equal(completion.registryCommitment, domain.registryCommitment, 'COMPLETION_REGISTRY');
    assert.equal(completion.context, core.context, 'COMPLETION_CONTEXT');
    assert.equal(completion.evidenceState, input.evidenceState, 'COMPLETION_DESCRIPTOR_STATE');
    assert.equal(completion.payoutCommitment, settlement.outputs[slot], 'COMPLETION_OUTPUT');
    bytes32(completion.payoutCommitment, true); bytes32(completion.terminalReceiptTag, true);
    assert.ok(!outputs.includes(completion.payoutCommitment), 'COMPLETION_DUPLICATE_OUTPUT');
    assert.ok(!terminalTags.includes(completion.terminalReceiptTag), 'COMPLETION_DUPLICATE_TAG');
    const completed = window(completion.validFrom, completion.validUntil, core.settleBefore);
    assert.ok(completed.from <= period.from && period.until <= completed.until, 'COMPLETION_SETTLEMENT_WINDOW');
    const seal = await codec.completionCommitment(d, packet.envelope, completion, supplied.blind);
    assert.equal(seal, n.completionCommitment, 'COMPLETION_SEAL');
    outputs.push(completion.payoutCommitment); terminalTags.push(completion.terminalReceiptTag); commitments.push(seal);
    completions.push(structToNoir('completion', completion)); blinds.push(digestBytes(supplied.blind));
  }
  const statement = { domainCommitment: d, authorizationRoot: c.authorization.root, evidenceState: input.evidenceState,
    poolRoot: reserve.root, reserveNullifier: settlement.reserveNullifier, outputs, terminalTags, completionCommitments: commitments,
    validFrom: input.validFrom, validUntil: input.validUntil };
  const inputs = { domain_commitment: digestWords(d), authorization_root: digestWords(c.authorization.root),
    evidence_state: digestWords(input.evidenceState), pool_root: digestWords(reserve.root),
    reserve_nullifier: digestWords(settlement.reserveNullifier), outputs: outputs.map(digestWords),
    terminal_tags: terminalTags.map(digestWords), completion_commitments: commitments.map(digestWords),
    valid_from: input.validFrom, valid_until: input.validUntil, ...c.common,
    settlement: structToNoir('settlement', settlement), settlement_blind: digestBytes(packet.settlement.blind),
    settlement_siblings: packet.settlement.siblings.map(digestBytes), completions, completion_blinds: blinds,
    reserve_siblings: reserve.siblings.map(digestBytes), reserve_index: reserve.index };
  return validateFlatInputs('settlement', options.abi, inputs, statement);
}
