const literal = text => `[${[...Buffer.from(text, 'utf8')].join(', ')}]`;
const paddedLength = n => Math.ceil((n + 9) / 64) * 64;

function renderFixed({ name, tag, fields }) {
  const parts = [{ constant: tag, size: Buffer.byteLength(tag) }, ...fields];
  const length = parts.reduce((sum, part) => sum + 4 + part.size, 0);
  const args = fields.filter(field => !field.constant)
    .map(field => `${field.name}: ${field.type ?? `[u8; ${field.size}]`}`);
  const lines = [
    `// ${tag}; every component, including this tag, has a u32BE length.`,
    `pub fn ${name}(\n    ${args.join(',\n    ')},\n) -> [u8; 32] {`,
    `    let mut message: [u8; ${length}] = [0; ${length}];`,
  ];
  let offset = 0;
  for (const field of parts) {
    const expression = field.constant ? literal(field.constant) : field.expression ?? field.name;
    lines.push(`    message = part(message, ${offset}, ${expression});`);
    offset += 4 + field.size;
  }
  lines.push(`    sha256::<${length}, ${paddedLength(length)}>(message)`, '}');
  return lines.join('\n');
}

function renderSalt() {
  const tag = 'LIANUM/PAEG/node-salt/1';
  const nonceOffset = 4 + Buffer.byteLength(tag);
  const idLengthOffset = nonceOffset + 4 + 32;
  const idOffset = idLengthOffset + 4;
  const maximum = idOffset + 64;
  return `// ${tag}; hash the actual ID length, never its 64-byte padding.
pub fn node_salt(nonce: [u8; 32], node_id: [u8; 64], id_length: u8) -> [u8; 32] {
    assert((id_length >= 1) & (id_length <= 64));
    let mut message: [u8; ${maximum}] = [0; ${maximum}];
    message = part(message, 0, ${literal(tag)});
    message = part(message, ${nonceOffset}, nonce);
    let length_bytes = u32_bytes(id_length as u32);
    for i in 0..4 { message[${idLengthOffset} + i] = length_bytes[i]; }
    for i in 0..64 { message[${idOffset} + i] = node_id[i]; }
    sha256_bounded::<${maximum}, ${paddedLength(maximum)}>(message, ${idOffset} + id_length as u32)
}`;
}

