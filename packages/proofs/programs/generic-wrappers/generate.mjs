// Source text only. This module never loads a compiler, backend or proof runtime.
import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { FUNDED_DOMAINS, FUNDED_GRAPH_PROFILE } from '@lianum/engine/execution/graph/funded-graph';

export const PROFILE = 'LIANUM_PAEG_FUNDED_4_V1';
export const ADMISSION_DOMAIN = 'LIANUM/PAEG/reservation-admission/1';
export const OFFICIAL_VERIFIER = new URL('../../../../scripts/engine/diagnostics/recursive-proof/circuits/recursive_join/src/bb_proof_verification.nr', import.meta.url);

export function renderFraming() {
  assert.equal(FUNDED_GRAPH_PROFILE.id, PROFILE, 'PAEG_WRAPPER_PROFILE_MISMATCH');
  assert.equal(FUNDED_GRAPH_PROFILE.intermediateWords, 139, 'PAEG_WRAPPER_A0_SIZE');
  assert.equal(FUNDED_DOMAINS.admission, ADMISSION_DOMAIN, 'PAEG_WRAPPER_ADMISSION_DOMAIN_MISMATCH');
  const fields = [Buffer.from(ADMISSION_DOMAIN), Buffer.from(PROFILE), ...['scope', 'policy', 'asset', 'operation_id']];
  const size = fields.reduce((n, value) => n + 4 + (Buffer.isBuffer(value) ? value.length : 32), 0);
  let offset = 0;
  const writes = fields.map(value => {
    const expression = Buffer.isBuffer(value) ? `[${[...value].join(', ')}]` : `words_to_bytes(${value})`;
    const line = `    message = part(message, ${offset}, ${expression});`;
    offset += 4 + (Buffer.isBuffer(value) ? value.length : 32);
    return line;
  }).join('\n');
  return `// Generated by generic-wrappers/generate.mjs; fixed profile, no witness specialization.
// Every H4 component, including the tag, has a u32BE byte-length prefix.
use generic_graph::sha256::{sha256, u32_bytes, words_to_bytes};

fn part<let N: u32, let M: u32>(buffer: [u8; N], offset: u32, value: [u8; M]) -> [u8; N] {
    let mut result = buffer;
    let length = u32_bytes(M);
    for i in 0..4 { result[offset + i] = length[i]; }
    for i in 0..M { result[offset + 4 + i] = value[i]; }
    result
}

// ${ADMISSION_DOMAIN}
pub fn admission(scope: [u32; 8], policy: [u32; 8], asset: [u32; 8], operation_id: [u32; 8]) -> [u32; 8] {
    let mut message: [u8; ${size}] = [0; ${size}];
${writes}
    let digest = sha256::<${size}, ${Math.ceil((size + 9) / 64) * 64}>(message);
    let mut words: [u32; 8] = [0; 8];
    for i in 0..8 {
        words[i] = (digest[i * 4] as u32 << 24) | (digest[i * 4 + 1] as u32 << 16)
            | (digest[i * 4 + 2] as u32 << 8) | digest[i * 4 + 3] as u32;
    }
    words
}
`;
}

export function generatedSources() {
  return new Map([
    ['lib/src/framing.nr', renderFraming()],
    ['lib/src/bb_proof_verification.nr', readFileSync(OFFICIAL_VERIFIER, 'utf8')],
  ]);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, source] of generatedSources()) {
    const target = new URL(path, import.meta.url);
    if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8'), source, `PAEG_WRAPPER_SOURCE_STALE: ${path}`);
    else {
      mkdirSync(new URL('../../../../packages/proofs/programs/generic-wrappers/lib/src/', import.meta.url), { recursive: true });
      writeFileSync(target, source);
    }
  }
  console.log('S66/F51 framing and official verifier source checked; no compilation or proof acceptance.');
}
