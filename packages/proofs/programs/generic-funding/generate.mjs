// Fixed byte contracts only. No topology, active count, keys or runtime values
// specialize this source. H4 and the exact legacy tag framing remain separate.
import { readFile, writeFile } from 'node:fs/promises';
import { FUNDED_DOMAINS, FUNDED_GRAPH_PROFILE } from '@lianum/engine/execution/graph/funded-graph';
const profile = Buffer.from(FUNDED_GRAPH_PROFILE.id);
const h = name => [name, 32];
const u = name => [name, 8];
const scope = [h('scope'), h('policy'), h('asset')];
const profileField = ['PROFILE', profile];
const specs = [
  ['reservation_intent', FUNDED_DOMAINS.intent, [profileField, ...scope, h('operation_id'), h('reservation_nonce'), u('budget'), u('settle_before'), h('recovery_commitment'), h('reserve_secret')]],
  ['reserved_note', FUNDED_DOMAINS.reserve, [profileField, ...scope, h('reservation_intent'), h('graph_commitment')]],
  ['admission', FUNDED_DOMAINS.admission, [profileField, ...scope, h('operation_id')]],
  ['empty_change', FUNDED_DOMAINS.emptyChange, [profileField, ...scope, h('input_nullifier'), h('operation_id'), h('reservation_nonce')]],
  ['payout_origin', FUNDED_DOMAINS.payoutOrigin, [...scope, h('operation_id'), ['slot', 1], h('randomness')]],
  ['empty_payout', FUNDED_DOMAINS.emptyPayout, [...scope, h('graph_commitment'), ['slot', 1], h('salt')]],
  ['invoice', FUNDED_DOMAINS.invoice, [profileField, ...scope, h('operation_id'), ['slot', 1], h('chain_domain'), h('evidence_policy'), h('action_commitment'), h('payout_commitment'), u('settle_before')]],
  ['owner_authorization', FUNDED_DOMAINS.owner, [profileField, ...scope, h('operation_id'), h('input_commitment'), h('input_nullifier'), h('reservation_intent'), h('graph_commitment'), h('tree_root'), h('reserve_commitment'), h('reserve_nullifier'), h('change_commitment'), h('output_0'), h('output_1'), h('output_2'), h('output_3'), h('recovery_commitment'), u('funding_not_before'), u('funding_valid_until'), u('settle_before')]],
  ['legacy_payment', 'PC15/payment-note/1', [h('scope'), h('origin'), ['kind', 1], h('key_x'), h('key_y'), u('value'), h('secret')], true],
  ['legacy_balance', 'PC23/balance-note/1', [h('scope'), h('policy'), ['TYPE4', Buffer.from([4])], h('rho'), h('key_x'), h('key_y'), u('value'), h('secret')], true],
  ['legacy_nullifier', 'PC15/note-spend/1', [h('scope'), h('commitment'), h('secret')], true],
];
const literal = bytes => `[${[...bytes].join(', ')}]`;
let source = `// Generated by generic-funding/generate.mjs from explicit byte contracts.\n// H4 uses a u32 tag length; PC15/PC23 use their original u16 tag length.\nuse generic_graph::sha256::{sha256, u32_bytes, u64_bytes};\n\nfn part<let N: u32, let M: u32>(buffer: [u8; N], offset: u32, value: [u8; M]) -> [u8; N] {\n    let mut result = buffer;\n    let length = u32_bytes(M);\n    for i in 0..4 { result[offset + i] = length[i]; }\n    for i in 0..M { result[offset + 4 + i] = value[i]; }\n    result\n}\n`;
for (const [name, domain, fields, legacy = false] of specs) {
  const tag = Buffer.from(domain);
  const parameters = fields.filter(([, width]) => typeof width === 'number');
  const size = tag.length + (legacy ? 2 : 4) + fields.reduce((n, [, width]) => n + 4 + (typeof width === 'number' ? width : width.length), 0);
  source += `\n// ${domain}; ${legacy ? 'legacy u16BE tag' : 'H4 u32BE tag'} framing.\npub fn ${name}(\n`;
  source += parameters.map(([key, width]) => `    ${key}: ${width === 8 ? 'u64' : `[u8; ${width}]`},`).join('\n');
  source += `\n) -> [u8; 32] {\n    let mut message: [u8; ${size}] = [0; ${size}];\n`;
  let offset = tag.length + (legacy ? 2 : 4);
  if (legacy) {
    source += `    message[0] = ${(tag.length >> 8)};\n    message[1] = ${tag.length & 255};\n    let tag = ${literal(tag)};\n    for i in 0..${tag.length} { message[2 + i] = tag[i]; }\n`;
  } else source += `    message = part(message, 0, ${literal(tag)});\n`;
  for (const [key, width] of fields) {
    const value = typeof width !== 'number' ? literal(width) : width === 8 ? `u64_bytes(${key})` : key;
    source += `    message = part(message, ${offset}, ${value});\n`;
    offset += 4 + (typeof width === 'number' ? width : width.length);
  }
  source += `    sha256::<${size}, ${Math.ceil((size + 9) / 64) * 64}>(message)\n}\n`;
}
const output = new URL('./lib/src/framing.nr', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== source) throw Error('PAEG_FUNDED_FRAMING_STALE');
} else await writeFile(output, source);
